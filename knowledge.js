/* تطبيع النص العربي للبحث: تشكيل، همزات، تاء مربوطة، أرقام هندية */
const DIACRITICS = /[\u0610-\u061A\u0640\u064B-\u065F\u0670\u06D6-\u06ED]/g;
function normalizeAr(s) {
  return (s || "")
    .replace(DIACRITICS, "")
    .replace(/[\u0622\u0623\u0625\u0671]/g, "\u0627")   // آ أ إ ٱ -> ا
    .replace(/\u0629/g, "\u0647")                        // ة -> ه
    .replace(/\u0649/g, "\u064A")                        // ى -> ي
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[^\u0600-\u06FF0-9a-zA-Z\s]/g, " ")
    .replace(/\s+/g, " ")
    .toLowerCase()
    .trim();
}

const STOP = new Set([
  "في", "من", "علي", "الى", "عن", "مع", "هذا", "هذه", "ذلك", "التي", "الذي",
  "ما", "هو", "هي", "انا", "انت", "ايه", "ازاي", "امتي", "او", "و", "يا",
  "the", "of", "and", "is", "a", "to", "in", "for", "on",
]);

function tokenize(s) {
  return normalizeAr(s)
    .split(" ")
    .filter((w) => w.length >= 2 && !STOP.has(w));
}

